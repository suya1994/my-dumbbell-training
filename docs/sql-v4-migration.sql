-- 9. 恢复后 / 迁移后序列修复
-- ------------------------------------------------------------
do $$
declare
  t       text;
  seq     text;
  max_id  bigint;
  last_id bigint;
begin
  foreach t in array array[
    'exercises','exercise_aliases','exercise_muscle_groups','user_equipment',
    'cycle_templates','cycle_template_exercises','plan_versions',
    'training_plans','training_plan_exercises','workouts',
    'workout_exercise_records','other_activities','body_metrics'
  ] loop
    seq := pg_get_serial_sequence('public.' || t, 'id');
    if seq is not null then
      execute format('select coalesce(max(id),0) from public.%I', t) into max_id;
      execute format('select last_value from %s', seq) into last_id;
      if max_id = 0 then
        execute format('select setval(%L, 1, false)', seq);
      else
        execute format('select setval(%L, %s, true)', seq, greatest(last_id, max_id));
      end if;
    end if;
  end loop;
end $$;

