-- 5.1 设备库：10/15/20 磅弹力带 + 5kg 哑铃
-- 兼容历史“弹力绳”命名：能改名则改名，目标名已存在则停用旧行，保证幂等且不产生重复设备。
do $$
declare
  r record;
  target_name text;
begin
  for r in
    select id, name from public.user_equipment
    where category = '弹力绳' or name like '弹力绳%'
  loop
    target_name := replace(r.name, '弹力绳', '弹力带');
    if not exists (
      select 1 from public.user_equipment
      where name = target_name and id <> r.id
    ) then
      update public.user_equipment
      set name = target_name,
          category = case when category = '弹力绳' then '弹力带' else category end,
          updated_at = now()
      where id = r.id;
    else
      update public.user_equipment
      set is_active = false,
          updated_at = now()
      where id = r.id;
    end if;
  end loop;
end $$;

