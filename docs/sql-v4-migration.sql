end $$;

create or replace function public.guard_completed_plan_update()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if old.status = 'completed' then
    if new.status is distinct from 'completed' then
      raise exception 'COMPLETED_PLAN_STATUS_IMMUTABLE';
    end if;
    if new.workout_number is distinct from old.workout_number then
      raise exception 'COMPLETED_PLAN_NUMBER_IMMUTABLE';
    end if;
  end if;
  return new;
end $$;

