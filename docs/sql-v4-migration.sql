-- 7. 外键迁移：workout_exercise_records.plan_exercise_id → RESTRICT
--    同时比对引用表/引用列/被引用表/被引用列/删除行为。
-- ------------------------------------------------------------
do $$
declare
  v_attnum   smallint;
  v_fattnum  smallint;
  v_conname  text;
begin
  select attnum into v_attnum
  from pg_attribute
  where attrelid = 'public.workout_exercise_records'::regclass
    and attname = 'plan_exercise_id'
    and not attisdropped;

  select attnum into v_fattnum
  from pg_attribute
  where attrelid = 'public.training_plan_exercises'::regclass
    and attname = 'id'
    and not attisdropped;

  if v_attnum is null or v_fattnum is null then
    raise exception 'FK MIGRATION: 找不到 plan_exercise_id 或 training_plan_exercises.id';
  end if;

  -- 已经是目标外键（列映射 + RESTRICT）→ 跳过
  select c.conname into v_conname
  from pg_constraint c
  where c.conrelid = 'public.workout_exercise_records'::regclass
    and c.contype = 'f'
    and c.confrelid = 'public.training_plan_exercises'::regclass
    and c.conkey = array[v_attnum]
    and c.confkey = array[v_fattnum]
    and c.confdeltype = 'r'
  limit 1;

  if v_conname is not null then
    return;
  end if;

  -- 只删除“同一列映射”的旧外键，不碰其他外键
  for v_conname in
    select c.conname
    from pg_constraint c
    where c.conrelid = 'public.workout_exercise_records'::regclass
      and c.contype = 'f'
      and c.confrelid = 'public.training_plan_exercises'::regclass
      and c.conkey = array[v_attnum]
      and c.confkey = array[v_fattnum]
  loop
    execute format(
      'alter table public.workout_exercise_records drop constraint %I',
      v_conname
    );
  end loop;

  if exists (
    select 1 from pg_constraint
    where conrelid='public.workout_exercise_records'::regclass
      and conname='werec_plan_exercise_fk'
  ) then
    execute 'alter table public.workout_exercise_records drop constraint werec_plan_exercise_fk';
  end if;

  alter table public.workout_exercise_records
    add constraint werec_plan_exercise_fk
    foreign key (plan_exercise_id)
    references public.training_plan_exercises(id)
    on delete restrict;
end $$;

